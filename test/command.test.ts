import { afterAll, beforeAll, describe, expect, inject, it, vi } from "vitest";
import { randomUUID } from "node:crypto";
import { z } from "zod";
import { createSession } from "@/auth/session";
import { handleCommand } from "@/lib/command";
import { getClient, getDb } from "@/lib/db";

// The shared route pipeline, driven as a route handler would: a signed session cookie and a JSON body.

let token = "";
vi.mock("next/headers", () => ({ cookies: async () => ({ get: () => ({ value: token }) }) }));

beforeAll(() => {
  process.env.MONGODB_URI = inject("mongoUri");
  process.env.MONGODB_DB = `t_cmd_${process.pid}_${Date.now()}`;
});
afterAll(async () => {
  await (await getDb()).dropDatabase();
  await (await getClient()).close();
});

let calls = 0;
const Input = z.object({ commandId: z.string(), n: z.number() });
const post = (name: string, body: unknown, target?: string) =>
  handleCommand(new Request("http://x/api", { method: "POST", body: JSON.stringify(body) }), {
    name,
    target,
    role: "manager",
    actionClass: "general",
    input: Input,
    run: async (_c, _s, _ctx, input) => ({ n: input.n, call: ++calls }),
  });

describe("commandId reuse", () => {
  it("replays the original result for the same command and body", async () => {
    token = createSession("manager").token;
    const commandId = randomUUID();
    const first = await (await post("demo", { commandId, n: 1 })).json();
    const again = await post("demo", { commandId, n: 1 });
    expect(again.status).toBe(200);
    expect(await again.json()).toEqual({ result: first.result, replayed: true });
  });

  it.each([
    ["a different body", "demo", { n: 2 }, false],
    ["a different command", "other", { n: 1 }, false],
    ["a different session", "demo", { n: 1 }, true],
    ["a different route target", "demo", { n: 1 }, false, "ST-2"],
  ] as const)("refuses %s with 409 COMMAND_ID_REUSED and runs nothing", async (_what, name, body, newSession, target: string = "ST-1") => {
    token = createSession("manager").token;
    const commandId = randomUUID();
    await post("demo", { commandId, n: 1 }, "ST-1");
    const before = calls;
    if (newSession) token = createSession("manager").token;
    const res = await post(name, { commandId, ...body }, target);
    expect(res.status).toBe(409);
    expect((await res.json()).error.code).toBe("COMMAND_ID_REUSED");
    expect(calls).toBe(before);
  });
});

// Generated by /ship coverage audit.
// Value: protects=each stocktake route puts its [id] in the fingerprint, so a commandId reused on another stocktake is refused;
// fails_when=a route drops `target: id` and replays the first stocktake's result for a different one; why_new=the table above
// drives handleCommand directly, not the routes; seam=none; no_claim=HTTP routing by Next (handlers called with params directly)
describe("stocktake routes fingerprint their [id]", () => {
  it("refuses a lines, submit or approve commandId reused on a different stocktake", async () => {
    const { migrate } = await import("@/seed/apply");
    const { buildWorld, runner, TOY } = await import("./world");
    const { openStocktake } = await import("@/domain/ledger/write");
    const lines = await import("@/app/api/stocktakes/[id]/lines/route");
    const submit = await import("@/app/api/stocktakes/[id]/submit/route");
    const approve = await import("@/app/api/stocktakes/[id]/approve/route");
    const db = await getDb();
    await migrate(db);
    await buildWorld(db);
    const clerk = createSession("clerk", "BR-A");
    const st = (await runner(await getClient(), db)((c, s, k) => openStocktake(c, s, k, { branchId: "BR-A", sid: clerk.session.sid, clerkLabel: "Clerk" }))).result;

    const steps = [
      [lines.POST, clerk.token, { sku: TOY, counted: 0, mode: "replace" }],
      [submit.POST, clerk.token, { uncounted: "leave" }],
      [approve.POST, createSession("manager").token, { acceptedKeys: [] }],
    ] as const;
    for (const [POST, as, body] of steps) {
      token = as;
      const data = JSON.stringify({ commandId: randomUUID(), ...body });
      const call = (id: string) => POST(new Request("http://x/api", { method: "POST", body: data }), { params: Promise.resolve({ id }) });
      expect((await call(st._id)).status).toBe(200);
      const other = await call("ST-other");
      expect(other.status).toBe(409);
      expect((await other.json()).error.code).toBe("COMMAND_ID_REUSED");
    }
  });
});

// The resume path a phone takes after a re-login: open without the key is BUSY, open with it takes over at once.
describe("stocktake resume key over the route", () => {
  it("hands out a key, never the nonce, and accepts only the latest key", async () => {
    const { migrate } = await import("@/seed/apply");
    const { buildWorld } = await import("./world");
    const open = await import("@/app/api/stocktakes/route");
    const db = await getDb();
    await db.dropDatabase();
    await migrate(db);
    await buildWorld(db);
    let id = "";
    const call = async (as: string, key?: string) => {
      token = as;
      const resume = key ? { stocktakeId: id, key } : undefined;
      const res = await open.POST(new Request("http://x/api", { method: "POST", body: JSON.stringify({ commandId: randomUUID(), resume }) }));
      return { status: res.status, body: await res.json() };
    };
    const first = await call(createSession("clerk", "BR-A").token);
    expect(first.status).toBe(200);
    expect(first.body.result.resumeKey).toMatch(/^[\w-]{20,}$/);
    expect(first.body.result).not.toHaveProperty("resumeNonce");
    id = first.body.result._id;

    const relogin = createSession("clerk", "BR-A").token;
    const busy = await call(relogin);
    expect(busy.status).toBe(409);
    expect(busy.body.error).toMatchObject({ code: "STOCKTAKE_BUSY", details: { stocktakeId: first.body.result._id } });
    expect((await call(relogin, "wrong-key")).status).toBe(409);
    const resumed = await call(relogin, first.body.result.resumeKey);
    expect(resumed.status).toBe(200);
    expect(resumed.body.result._id).toBe(first.body.result._id);
    expect(resumed.body.result.resumeKey).not.toBe(first.body.result.resumeKey);
    expect((await call(createSession("clerk", "BR-A").token, first.body.result.resumeKey)).status).toBe(409); // rotated
  });
});

describe("resume key helpers", () => {
  it("ties the key to the stocktake and nonce", async () => {
    const { resumeKeyFor, resumeKeyMatches } = await import("@/auth/session");
    const key = resumeKeyFor("ST-1", "n1");
    expect(resumeKeyMatches("ST-1", "n1", key)).toBe(true);
    expect(resumeKeyMatches("ST-2", "n1", key)).toBe(false);
    expect(resumeKeyMatches("ST-1", "n2", key)).toBe(false);
    expect(resumeKeyMatches("ST-1", "n1", key.slice(0, -1))).toBe(false);
    expect(resumeKeyMatches("ST-1", undefined, key)).toBe(false);
  });
});

// Clerks count blind: a refused sale names the short lines but never the system quantity.
describe("sale route", () => {
  it("refuses short stock without revealing on-hand", async () => {
    const { migrate } = await import("@/seed/apply");
    const { buildWorld, TOY } = await import("./world");
    const sales = await import("@/app/api/sales/route");
    const db = await getDb();
    await db.dropDatabase();
    await migrate(db);
    await buildWorld(db);
    token = createSession("clerk", "BR-A").token;
    const post = (lines: unknown) => sales.POST(new Request("http://x/api", { method: "POST", body: JSON.stringify({ commandId: randomUUID(), lines }) }));
    const res = await post([{ sku: TOY, qty: 999 }]);
    expect(res.status).toBe(409);
    const body = await res.json();
    expect(body.error).toMatchObject({ code: "INSUFFICIENT_STOCK", details: [{ sku: TOY }] });
    expect(JSON.stringify(body)).not.toMatch(/available|System shows/);
    expect((await post([{ sku: TOY, qty: 1 }, { sku: TOY, qty: 1 }])).status).toBe(400); // duplicate lines
  });
});
